package brief

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
)

// Block markers of the managed block.
const (
	StartMarker = "<!-- agentbrief:start -->"
	EndMarker   = "<!-- agentbrief:end -->"
)

const generatedLine = "_Generated by [AgentBrief](https://github.com/seanmcmahon101/AgentBrief) from repository files; do not edit inside this block. Refresh with `agentbrief sync`._"

// MaxLines is the soft budget for the Markdown body.
const MaxLines = 40

// JSON renders the brief with 2-space indentation and a trailing newline.
func (b Brief) JSON() ([]byte, error) {
	// Encoder rather than MarshalIndent so `<file>` placeholders in commands
	// are not escaped to \u003cfile\u003e, which agents read poorly.
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(b); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// Markdown returns the managed block, markers included, without a trailing newline.
func (b Brief) Markdown() string {
	return StartMarker + "\n" + b.Body() + EndMarker
}

// codeSpan wraps s in a backtick code span, safe for embedded backticks.
func codeSpan(s string) string {
	max, cur := 0, 0
	for _, r := range s {
		if r == '`' {
			cur++
			if cur > max {
				max = cur
			}
		} else {
			cur = 0
		}
	}
	if max == 0 {
		return "`" + s + "`"
	}
	fence := strings.Repeat("`", max+1)
	return fence + " " + s + " " + fence
}

func dirPhrase(dir string) string {
	if dir == "." {
		return "the repo root"
	}
	return codeSpan(dir)
}

func sentenceList(items []string, conj string) string {
	switch len(items) {
	case 0:
		return ""
	case 1:
		return items[0]
	}
	return strings.Join(items[:len(items)-1], ", ") + " " + conj + " " + items[len(items)-1]
}

var toolDisplay = map[string]string{
	"node": "Node", "go": "Go", "python": "Python", "rust": "Rust", "java": "Java", "ruby": "Ruby",
	"php": "PHP", "dotnet": ".NET", "deno": "Deno", "bun": "Bun", "elixir": "Elixir", "swift": "Swift",
	"kotlin": "Kotlin", "erlang": "Erlang", "zig": "Zig",
}

func displayTool(n string) string {
	if d, ok := toolDisplay[n]; ok {
		return d
	}
	return n
}

// Body returns the block contents between the markers (heading through last
// fact), ending with a newline. Deterministic: no timestamps or absolute paths.
func (b Brief) Body() string {
	for notes := len(b.Notes); ; notes-- {
		s := b.body(notes)
		if notes <= 0 || strings.Count(s, "\n")+2 <= MaxLines {
			return s
		}
	}
}

func (b Brief) body(maxNotes int) string {
	var w strings.Builder
	line := func(f string, a ...any) { fmt.Fprintf(&w, f+"\n", a...) }

	line("## Repository facts")
	line("")
	line("%s", generatedLine)
	line("")

	// ---- toolchain and package managers (validated)
	var parts []string
	for _, t := range b.Toolchain {
		if !validName(t.Name) || !validVersion(t.Version) {
			continue
		}
		p := displayTool(t.Name) + " " + t.Version
		var src []string
		for _, s := range t.Sources {
			if validPath(s) {
				src = append(src, codeSpan(s))
			}
		}
		if len(src) > 0 {
			p += " (" + strings.Join(src, ", ") + ")"
		}
		parts = append(parts, p)
	}
	var avoid []string
	for _, pm := range b.PackageManagers {
		if !validName(pm.Name) {
			continue
		}
		p := pm.Name
		if pm.Version != "" && validVersion(pm.Version) {
			p += " " + pm.Version
		}
		if pm.Source != "" && validPath(pm.Source) {
			p += " (" + codeSpan(pm.Source) + ")"
		}
		parts = append(parts, p)
		if len(pm.Avoid) > 0 {
			avoid = append(avoid, fmt.Sprintf("Use %s, not %s.", pm.Name, sentenceList(pm.Avoid, "or")))
		}
	}

	var cmdLines []string
	cmds := b.renderCommands()
	var ws []string
	if b.Workspace != nil {
		ws = b.renderWorkspace()
	}
	var dne []string
	for _, d := range b.DoNotEdit {
		switch {
		case len(d.Patterns) > 0:
			var l []string
			for _, p := range d.Patterns {
				if validPattern(p) {
					l = append(l, codeSpan(p))
				}
			}
			if len(l) > 0 {
				dne = append(dne, "lockfiles "+strings.Join(l, ", "))
			}
		case validPattern(d.Pattern) && d.Reason != "" && validReason(d.Reason):
			dne = append(dne, codeSpan(d.Pattern)+" ("+d.Reason+")")
		case validPattern(d.Pattern) && d.Reason == "":
			dne = append(dne, codeSpan(d.Pattern))
		}
	}
	_ = cmdLines

	if len(parts) == 0 && len(cmds) == 0 && len(ws) == 0 && len(dne) == 0 {
		line("- No toolchain, command or package-manager facts could be derived from this repository.")
	}
	if b.Project != nil && validPath(b.Project.Dir) {
		s := "- Scope: " + codeSpan(b.Project.Dir)
		if b.Project.Name != "" && b.Project.Name != b.Project.Dir && validPkg(b.Project.Name) {
			s += " (" + codeSpan(b.Project.Name) + ")"
		}
		line("%s", s)
	} else if b.Scope != "." && validPath(b.Scope) {
		line("- Scope: %s", codeSpan(b.Scope))
	}
	if len(parts) > 0 {
		s := "- Toolchain: " + strings.Join(parts, ", ") + "."
		if len(avoid) > 0 {
			s += " " + strings.Join(avoid, " ")
		}
		line("%s", s)
	}
	if len(b.Ecosystems) > 1 {
		var e []string
		for _, p := range b.Ecosystems {
			if !validName(p.Ecosystem) {
				continue
			}
			s := p.Ecosystem
			if p.Manifest != "" && validPath(p.Manifest) {
				s += " (" + codeSpan(p.Manifest) + ")"
			}
			e = append(e, s)
		}
		if len(e) > 1 && validPath(b.Scope) {
			line("- Ecosystems at %s: %s.", dirPhrase(b.Scope), strings.Join(e, ", "))
		}
	}
	if len(cmds) > 0 {
		line("")
		for _, l := range cmds {
			line("%s", l)
		}
	}
	if b.OtherBuildTool != nil && validName(strings.ToLower(b.OtherBuildTool.Tool)) {
		line("")
		line("%s build also present: %s.", b.OtherBuildTool.Tool, codeSpan(b.OtherBuildTool.Run))
	}
	if len(ws) > 0 {
		line("")
		for _, l := range ws {
			line("%s", l)
		}
	}
	if len(dne) > 0 {
		line("")
		line("Do not edit by hand: %s.", strings.Join(dne, ", "))
	}

	// ---- other instruction files
	var files []string
	for _, f := range b.InstructionFiles {
		if validPath(strings.TrimSuffix(f, "/")) {
			files = append(files, f)
		}
	}
	if len(files) > 0 {
		line("")
		var l []string
		for i, f := range files {
			if i >= MaxInstructions {
				l = append(l, fmt.Sprintf("… (+%d more)", len(files)-MaxInstructions))
				break
			}
			l = append(l, codeSpan(f))
		}
		line("Other agent instructions: %s.", strings.Join(l, ", "))
	}

	// ---- notes
	if maxNotes > 0 && len(b.Notes) > 0 {
		line("")
		line("Notes:")
		for i, n := range b.Notes {
			if i >= maxNotes {
				break
			}
			line("- %s", n)
		}
	}
	return w.String()
}

func (b Brief) renderCommands() []string {
	var order []string
	groups := map[string][]Command{}
	for _, c := range b.Commands {
		if !validPath(c.Dir) && c.Dir != "." {
			continue
		}
		if _, ok := groups[c.Dir]; !ok {
			order = append(order, c.Dir)
		}
		groups[c.Dir] = append(groups[c.Dir], c)
	}
	var out []string
	for i, d := range order {
		head := "Commands (run from " + dirPhrase(d) + "):"
		if i > 0 {
			head = "More commands (run from " + dirPhrase(d) + "):"
		}
		out = append(out, head)
		for _, c := range groups[d] {
			s := fmt.Sprintf("- %s: %s (%s)", KindLabel(c.Kind), codeSpan(c.Run), c.Label)
			if c.Adapted {
				s = fmt.Sprintf("- %s: %s (%s, adapted to this crate)", KindLabel(c.Kind), codeSpan(c.Run), c.Label)
			}
			if c.Alternate != nil {
				s += fmt.Sprintf("; also %s (%s)", codeSpan(c.Alternate.Run), c.Alternate.Label)
			}
			if c.Note != "" {
				s += " — " + c.Note
			}
			out = append(out, s)
		}
	}
	return out
}

func (b Brief) renderWorkspace() []string {
	ws := b.Workspace
	var members []string
	for _, m := range ws.Members {
		if !validPath(m.Dir) {
			continue
		}
		s := codeSpan(m.Dir)
		named := m.Name != "" && m.Name != m.Dir && !strings.HasSuffix(m.Dir, "/"+m.Name) && validPkg(m.Name)
		if ws.Kind == "workspace" {
			if named {
				s += " (" + codeSpan(m.Name) + ")"
			}
		} else if validName(m.Ecosystem) {
			e := m.Ecosystem
			if named {
				e += ", " + codeSpan(m.Name)
			}
			s += " (" + e + ")"
		}
		members = append(members, s)
	}
	if len(members) == 0 {
		return nil
	}
	if ws.Omitted > 0 || len(members) < len(ws.Members) {
		members = append(members, "…")
	}
	label, unit := "Projects", "project"
	if ws.Kind == "workspace" {
		label, unit = "Workspace", "package"
	}
	count := fmt.Sprintf("%d", ws.Count)
	if ws.Capped {
		count += "+"
	}
	if ws.Count != 1 || ws.Capped {
		unit += "s"
	}
	head := count + " " + unit
	if ws.Manager != "" && validName(ws.Manager) {
		head = ws.Manager + ", " + head
	}
	return []string{fmt.Sprintf("%s (%s): %s — per-package commands: `agentbrief brief <dir>` (if installed), otherwise see each package's manifest.", label, head, strings.Join(members, ", "))}
}
