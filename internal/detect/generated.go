package detect

import (
	"bufio"
	"bytes"
	"path"
	"regexp"
	"sort"
	"strings"

	"github.com/seanmcmahon101/AgentBrief/internal/model"
	"github.com/seanmcmahon101/AgentBrief/internal/scan"
)

func init() { register("generated", detectGenerated) }

const (
	maxGeneratedRules = 25
	maxHeaderFiles    = 3000
	headerBytes       = 512
	// A directory is reported as "dir/**" when this share of its source
	// files carry a generated marker and there are at least minCollapse.
	collapseRatio = 0.8
	minCollapse   = 3
	// maxNestedLockfiles bounds lockfiles found below the repository root.
	maxNestedLockfiles = 8
)

var lockfileNames = map[string]bool{
	"package-lock.json": true, "npm-shrinkwrap.json": true, "pnpm-lock.yaml": true, "yarn.lock": true,
	"bun.lock": true, "bun.lockb": true, "Cargo.lock": true, "poetry.lock": true, "uv.lock": true,
	"pdm.lock": true, "Pipfile.lock": true, "Gemfile.lock": true, "composer.lock": true,
	"go.sum": true, "mix.lock": true, "Package.resolved": true, "flake.lock": true, "gradle.lockfile": true,
}

// generatedSuffixes are file-name conventions of code generators. They are only
// reported when such a file exists in the repository.
var generatedSuffixes = []string{
	".pb.go", "_pb2.py", "_pb2_grpc.py", ".pb.cc", ".pb.h", ".g.dart", ".Designer.cs", ".min.js",
}

// generatedMarker matches the standard "this file is generated" headers.
var generatedMarker = regexp.MustCompile(
	`Code generated .* DO NOT EDIT|@generated|<auto-generated|` +
		`This file (?:is|was) (?:automatically |auto-?)?generated|Generated by the protocol buffer compiler`)

// sourceExts are the extensions worth sniffing for a generated header.
var sourceExts = func() map[string]bool {
	m := map[string]bool{".proto": true, ".graphql": true, ".sql": true, ".xaml": true}
	for e := range langByExt {
		m[e] = true
	}
	return m
}()

// codegenNames hints that a file is likely generated, so it is scanned first
// when the header-scan budget cannot cover the whole repository.
var codegenNames = []string{"gen", "pb", "auto", "schema", "bindata", "bundle", "mock", "stub", "types", "api"}

func detectGenerated(r *scan.Repo, f *Facts) {
	attrs := gitattributesRules(r)
	dirs, files := headerRules(r, attrs)
	locks := lockfileRules(r)
	// Order is significance: explicit attributes, whole generated trees,
	// naming-convention globs, root lockfiles, individual files, nested lockfiles.
	var rules []model.PathRule
	rules = append(rules, attrs...)
	rules = append(rules, dirs...)
	rules = append(rules, suffixRules(r)...)
	rootLocks := 0
	for rootLocks < len(locks) && !strings.Contains(locks[rootLocks].Pattern, "/") {
		rootLocks++
	}
	rules = append(rules, locks[:rootLocks]...)
	rules = append(rules, files...)
	rules = append(rules, locks[rootLocks:]...)
	added := 0
	for _, rule := range rules {
		if added >= maxGeneratedRules {
			break
		}
		n := len(f.Generated)
		f.AddGenerated(rule)
		added += len(f.Generated) - n
	}
}

// gitattributesRules reads linguist-generated / linguist-vendored attributes.
// Later lines override earlier ones for the same pattern.
func gitattributesRules(r *scan.Repo) []model.PathRule {
	var files []string
	for _, p := range r.Files() {
		if path.Base(p) == ".gitattributes" && !isVendoredPath(p) {
			files = append(files, p)
		}
	}
	var out []model.PathRule
	for _, file := range files {
		dir := path.Dir(file)
		sc := bufio.NewScanner(strings.NewReader(r.ReadString(file)))
		for n := 1; sc.Scan(); n++ {
			fields := strings.Fields(sc.Text())
			if len(fields) < 2 || strings.HasPrefix(fields[0], "#") {
				continue
			}
			reason, on := linguistAttr(fields[1:])
			if reason == "" {
				continue
			}
			pat := fields[0]
			if dir != "." {
				pat = path.Join(dir, strings.TrimPrefix(pat, "/"))
			}
			out = removePattern(out, pat)
			if on {
				out = append(out, model.PathRule{Pattern: pat, Reason: reason, Source: model.Source{Path: file, Line: n}})
			}
		}
	}
	return out
}

// linguistAttr interprets the attribute list of one .gitattributes line.
func linguistAttr(attrs []string) (reason string, on bool) {
	for _, a := range attrs {
		name, val, hasVal := strings.Cut(a, "=")
		neg := strings.HasPrefix(name, "-") || strings.HasPrefix(name, "!")
		name = strings.TrimLeft(name, "-!")
		var r string
		switch name {
		case "linguist-generated":
			r = "generated"
		case "linguist-vendored":
			r = "vendored"
		default:
			continue
		}
		reason = r
		on = !neg && (!hasVal || val == "true")
	}
	return reason, on
}

func removePattern(rules []model.PathRule, pat string) []model.PathRule {
	out := rules[:0]
	for _, r := range rules {
		if r.Pattern != pat {
			out = append(out, r)
		}
	}
	return out
}

type genHit struct {
	file string
	line int
}

// headerRules finds generated files by their header comment, collapsing dense
// directories into "dir/**" so a code generator's output tree is one rule.
func headerRules(r *scan.Repo, already []model.PathRule) (dirRules, fileRules []model.PathRule) {
	var candidates []string
	srcPerDir := map[string]int{}
	for _, p := range r.Files() {
		if !sourceExts[strings.ToLower(path.Ext(p))] || isVendoredPath(p) || hasFixtureDir(p) {
			continue
		}
		candidates = append(candidates, p)
		for d := path.Dir(p); d != "."; d = path.Dir(d) {
			srcPerDir[d]++
		}
	}
	candidates = prioritise(candidates)
	if len(candidates) > maxHeaderFiles {
		candidates = candidates[:maxHeaderFiles]
	}

	var hits []genHit
	for _, p := range candidates {
		if hasSuffixIn(p, generatedSuffixes) || coveredBy(already, p) {
			continue // reported by a suffix glob or an explicit attribute
		}
		head, err := r.Head(p, headerBytes)
		if err != nil {
			continue
		}
		if line := markerLine(head); line > 0 {
			hits = append(hits, genHit{p, line})
		}
	}
	sort.Slice(hits, func(i, j int) bool { return hits[i].file < hits[j].file })

	// Count hits per ancestor directory, then pick the shallowest dense ones.
	genPerDir := map[string]int{}
	for _, h := range hits {
		for d := path.Dir(h.file); d != "."; d = path.Dir(d) {
			genPerDir[d]++
		}
	}
	// A directory holding a denser generated subdirectory is only collapsed
	// when everything in it is generated, so a hand-written file next to a
	// generated tree is not swallowed by "parent/**".
	var dirs []string
	for d, n := range genPerDir {
		need := collapseRatio
		if hasDenseDescendant(genPerDir, srcPerDir, d) {
			need = 1
		}
		if n >= minCollapse && float64(n) >= need*float64(srcPerDir[d]) {
			dirs = append(dirs, d)
		}
	}
	sort.Slice(dirs, func(i, j int) bool {
		di, dj := strings.Count(dirs[i], "/"), strings.Count(dirs[j], "/")
		if di != dj {
			return di < dj
		}
		return dirs[i] < dirs[j]
	})
	var chosen []string
	for _, d := range dirs {
		if !underAny(chosen, d) {
			chosen = append(chosen, d)
		}
	}
	// Most files first: a big generated tree matters more than a small one.
	sort.SliceStable(chosen, func(i, j int) bool { return genPerDir[chosen[i]] > genPerDir[chosen[j]] })

	for _, d := range chosen {
		first := firstHitUnder(hits, d)
		dirRules = append(dirRules, model.PathRule{Pattern: d + "/**", Reason: "generated", Source: model.Source{Path: first.file, Line: first.line}})
	}
	for _, h := range hits {
		if !underAny(chosen, h.file) {
			fileRules = append(fileRules, model.PathRule{Pattern: h.file, Reason: "generated", Source: model.Source{Path: h.file, Line: h.line}})
		}
	}
	return dirRules, fileRules
}

func hasDenseDescendant(gen, src map[string]int, dir string) bool {
	for d, n := range gen {
		if strings.HasPrefix(d, dir+"/") && n >= minCollapse && float64(n) >= collapseRatio*float64(src[d]) {
			return true
		}
	}
	return false
}

// prioritise puts files with generator-ish names first, keeping order stable.
func prioritise(files []string) []string {
	var hot, rest []string
	for _, p := range files {
		base := strings.ToLower(path.Base(p))
		dir := strings.ToLower(path.Dir(p))
		hotName := false
		for _, k := range codegenNames {
			if strings.Contains(base, k) || strings.Contains(dir, k) {
				hotName = true
				break
			}
		}
		if hotName {
			hot = append(hot, p)
		} else {
			rest = append(rest, p)
		}
	}
	return append(hot, rest...)
}

// markerLine returns the 1-based line of a generated marker inside a comment
// in head, or 0. Requiring a comment prefix avoids matching code or string
// literals that merely mention the marker.
func markerLine(head []byte) int {
	for i, line := range bytes.Split(head, []byte("\n")) {
		t := bytes.TrimSpace(line)
		if len(t) == 0 || !isCommentLine(t) {
			continue
		}
		if generatedMarker.Match(t) {
			return i + 1
		}
	}
	return 0
}

func isCommentLine(t []byte) bool {
	for _, p := range []string{"//", "#", "/*", "*", "--", "<!--", `"""`, "'''", ";", "%", "'", "<#"} {
		if bytes.HasPrefix(t, []byte(p)) {
			return true
		}
	}
	return false
}

func firstHitUnder(hits []genHit, dir string) genHit {
	for _, h := range hits {
		if strings.HasPrefix(h.file, dir+"/") {
			return h
		}
	}
	return genHit{file: dir}
}

func underAny(dirs []string, p string) bool {
	for _, d := range dirs {
		if p == d || strings.HasPrefix(p, d+"/") {
			return true
		}
	}
	return false
}

func hasSuffixIn(p string, suffixes []string) bool {
	for _, s := range suffixes {
		if strings.HasSuffix(p, s) {
			return true
		}
	}
	return false
}

// coveredBy reports whether an explicit .gitattributes rule already names p.
func coveredBy(rules []model.PathRule, p string) bool {
	for _, r := range rules {
		pat := strings.TrimPrefix(r.Pattern, "/")
		if scan.MatchPath(pat, p) || scan.MatchPath(strings.TrimSuffix(pat, "/")+"/**", p) ||
			(!strings.Contains(pat, "/") && scan.MatchPath(pat, path.Base(p))) {
			return true
		}
	}
	return false
}

// suffixRules emits one glob per generator naming convention that is present.
func suffixRules(r *scan.Repo) []model.PathRule {
	first := map[string]string{}
	for _, p := range r.Files() {
		if isVendoredPath(p) || hasFixtureDir(p) {
			continue
		}
		for _, s := range generatedSuffixes {
			if _, seen := first[s]; !seen && strings.HasSuffix(p, s) && len(path.Base(p)) > len(s) {
				first[s] = p
			}
		}
	}
	var out []model.PathRule
	for _, s := range generatedSuffixes {
		if p, ok := first[s]; ok {
			out = append(out, model.PathRule{Pattern: "*" + s, Reason: "generated", Source: model.Source{Path: p}})
		}
	}
	return out
}

// lockfileRules lists committed lockfiles, root-level ones first.
func lockfileRules(r *scan.Repo) []model.PathRule {
	var found []string
	for _, p := range r.Files() {
		if lockfileNames[path.Base(p)] && !isVendoredPath(p) && !hasFixtureDir(p) && !hasDemoDir(p) {
			found = append(found, p)
		}
	}
	sort.SliceStable(found, func(i, j int) bool {
		return strings.Count(found[i], "/") < strings.Count(found[j], "/")
	})
	// Deeply nested lockfiles are usually test inputs; keep the shallow few.
	kept, nested := found[:0], 0
	for _, p := range found {
		if depth := strings.Count(p, "/"); depth > 0 && (depth > 2 || nested >= maxNestedLockfiles) {
			continue
		} else if depth > 0 {
			nested++
		}
		kept = append(kept, p)
	}
	found = kept
	out := make([]model.PathRule, 0, len(found))
	for _, p := range found {
		out = append(out, model.PathRule{Pattern: p, Reason: "lockfile", Source: model.Source{Path: p}})
	}
	return out
}
