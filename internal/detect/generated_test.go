package detect

import (
	"fmt"
	"strings"
	"testing"

	"github.com/seanmcmahon101/AgentBrief/internal/model"
)

func patterns(rules []model.PathRule) []string {
	var out []string
	for _, r := range rules {
		out = append(out, r.Pattern+"|"+r.Reason)
	}
	return out
}

func wantPatterns(t *testing.T, got []model.PathRule, want ...string) {
	t.Helper()
	g := strings.Join(patterns(got), "\n")
	w := strings.Join(want, "\n")
	if g != w {
		t.Errorf("rules mismatch\n got:\n%s\nwant:\n%s", g, w)
	}
}

func TestGeneratedGitattributes(t *testing.T) {
	f := runOnly(map[string]string{
		".gitattributes":     "# c\n*.snap linguist-generated\ndocs/** linguist-vendored=true\nkeep.go linguist-generated\nkeep.go -linguist-generated\n*.txt text\n",
		"sub/.gitattributes": "gen.go linguist-generated=true\n",
	}, detectGenerated)
	wantPatterns(t, f.Generated, "*.snap|generated", "docs/**|vendored", "sub/gen.go|generated")
	if f.Generated[0].Source.Path != ".gitattributes" || f.Generated[0].Source.Line != 2 {
		t.Errorf("source = %+v", f.Generated[0].Source)
	}
}

func TestGeneratedHeaders(t *testing.T) {
	files := map[string]string{
		"main.go":         "package main\n",
		"api/a.go":        "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n",
		"api/doc.go":      "package api\n",
		"web/x.ts":        "/* @generated */\n",
		"web/real.ts":     "export const x = 1\n",
		"web/real2.ts":    "export const y = 1\n",
		"web/real3.ts":    "export const y = 1\n",
		"cs/A.cs":         "//------\n// <auto-generated>\n//   tool\n",
		"py/mod.py":       "# This file was automatically generated by foo\nx = 1\n",
		"notcomment.go":   "package x\nvar s = \"Code generated by hand DO NOT EDIT\"\n",
		"cc/a.pb.h":       "// Generated by the protocol buffer compiler.  DO NOT EDIT!\n",
		"vendor/g/gen.go": "// Code generated by x. DO NOT EDIT.\n",
	}
	f := runOnly(files, detectGenerated)
	wantPatterns(t, f.Generated, "*.pb.h|generated", "api/a.go|generated", "cs/A.cs|generated", "py/mod.py|generated", "web/x.ts|generated")
	for _, r := range f.Generated {
		if r.Pattern == "api/a.go" && r.Source.Line != 1 {
			t.Errorf("line = %d", r.Source.Line)
		}
	}
}

func TestGeneratedDirectoryCollapse(t *testing.T) {
	files := map[string]string{"src/app.ts": "x", "src/gen/README.md": "x"}
	for i := 0; i < 10; i++ {
		files[fmt.Sprintf("src/gen/deep/f%d.ts", i)] = "// @generated\n"
		files[fmt.Sprintf("src/gen/g%d.ts", i)] = "// @generated\n"
	}
	// Sparse: 3 of 10 generated stays as files.
	for i := 0; i < 10; i++ {
		body := "x\n"
		if i < 3 {
			body = "// @generated\n"
		}
		files[fmt.Sprintf("lib/m%d.ts", i)] = body
	}
	f := runOnly(files, detectGenerated)
	wantPatterns(t, f.Generated, "src/gen/**|generated", "lib/m0.ts|generated", "lib/m1.ts|generated", "lib/m2.ts|generated")
}

func TestGeneratedSuffixesAndLockfiles(t *testing.T) {
	f := runOnly(map[string]string{
		"a/x.pb.go": "package a", "b/y.pb.go": "package b", "z_pb2.py": "x", "static/app.min.js": "x",
		"pnpm-lock.yaml": "x", "web/package-lock.json": "{}", "go.sum": "x", "Cargo.lock": "x",
		"node_modules/q/package-lock.json": "{}", "vendor/x/go.sum": "x",
	}, detectGenerated)
	wantPatterns(t, f.Generated,
		"*.pb.go|generated", "*_pb2.py|generated", "*.min.js|generated",
		"Cargo.lock|lockfile", "go.sum|lockfile", "pnpm-lock.yaml|lockfile", "web/package-lock.json|lockfile")
}

